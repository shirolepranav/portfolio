// Makes the landing's blurred island placeholders: each still shrunk to a few dozen pixels, as WebP, written into
// src/components/island-placeholders.ts as data URIs. They sit inside the page itself, so the island's shape shows
// with the text at first paint, before the sharp still arrives over the network.
// Run after changing a landing still: node scripts/make-placeholders.mjs (uses sharp, which Astro already installs).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const STILLS = {
  dayPhone: "landing-island-day-phone.jpg",
  dayDesktop: "landing-island-day-desktop.jpg",
  nightPhone: "map-island-night-phone.jpg",
  nightDesktop: "landing-island-night-desktop.jpg",
};
const WIDTH = { Phone: 24, Desktop: 40 }; // pixels across: enough for the island's shape, about 300 to 600 bytes each

let out = "// Generated by scripts/make-placeholders.mjs. Do not edit: run the script again after changing a landing still.\n";
out += "// Tiny blurred WebP copies of the landing stills, as data URIs (see src/components/IslandStill.astro).\n";
for (const [name, file] of Object.entries(STILLS)) {
  const width = WIDTH[name.endsWith("Phone") ? "Phone" : "Desktop"];
  const buf = await sharp(fileURLToPath(new URL(`../src/assets/${file}`, import.meta.url))).resize({ width }).webp({ quality: 60 }).toBuffer();
  out += `export const ${name} = "data:image/webp;base64,${buf.toString("base64")}"; // ${buf.length} bytes\n`;
  console.log(name, buf.length, "bytes");
}
writeFileSync(new URL("../src/components/island-placeholders.ts", import.meta.url), out);
